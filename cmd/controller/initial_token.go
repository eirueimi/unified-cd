package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"

	"github.com/eirueimi/unified-cd/internal/controller"
	"github.com/eirueimi/unified-cd/internal/store"
)

// errNoWritableDir is returned by prepareInitialToken when the initial admin
// token has to be written to a file but none of the candidate directories
// accepts one.
var errNoWritableDir = errors.New("no writable config or data directory")

const (
	// devInitialAdminToken is the value the repo-root docker-compose.yaml
	// publishes for its local dev stack. Anyone can read it, so it is only
	// accepted in dev mode.
	devInitialAdminToken = "uci_dev0000000000000000000000000000000000000"

	// minProvidedInitialTokenLen is the shortest UNIFIED_INITIAL_ADMIN_TOKEN
	// accepted.
	minProvidedInitialTokenLen = 24
)

// validateProvidedInitialToken checks a UNIFIED_INITIAL_ADMIN_TOKEN value
// before it is stored. An empty value is fine (nothing is provided). The
// published dev value is refused unless dev mode (UNIFIED_DEV_MODE) is set, and
// every provided value needs at least 24 characters.
func validateProvidedInitialToken(provided string, devMode bool) error {
	if provided == "" {
		return nil
	}
	if len(provided) < minProvidedInitialTokenLen {
		return fmt.Errorf("UNIFIED_INITIAL_ADMIN_TOKEN is too short: use at least %d characters", minProvidedInitialTokenLen)
	}
	if provided == devInitialAdminToken && !devMode {
		return errors.New("UNIFIED_INITIAL_ADMIN_TOKEN is the published development value; set your own value or UNIFIED_DEV_MODE=1 for a throwaway setup")
	}
	return nil
}

// initialTokenDirs returns the directories the initial admin token file may be
// written to, in order: the config file directory (only when a config file is
// used), then the data directory (only when set).
func initialTokenDirs(configFile, dataDir string) []string {
	var dirs []string
	if configFile != "" {
		dirs = append(dirs, filepath.Dir(configFile))
	}
	if dataDir != "" {
		dirs = append(dirs, dataDir)
	}
	return dirs
}

// prepareInitialToken makes the one-time initial admin token available at
// startup (spec 6.4).
//
//   - Bootstrap already done: a leftover initial-admin-token file in dirs is
//     deleted.
//   - provided (UNIFIED_INITIAL_ADMIN_TOKEN) is stored as the token's hash
//     whether or not SSO is configured; no file is written.
//   - Otherwise, without SSO, a token is generated, its hash stored (only one
//     replica wins) and the value written to the first writable directory of
//     dirs. The returned path is that file; it is empty when nothing was
//     written.
//
// The value is never logged.
func prepareInitialToken(ctx context.Context, st store.Store, sso bool, provided string, dirs []string) (string, error) {
	state, err := st.GetBootstrapState(ctx)
	if err != nil {
		return "", fmt.Errorf("read bootstrap state: %w", err)
	}
	if state.Done {
		for _, p := range controller.RemoveInitialTokenFiles(dirs) {
			slog.Info("removed the used initial admin token file " + p)
		}
		return "", nil
	}

	if provided != "" {
		hash := controller.HashToken(provided)
		stored, err := st.ClaimInitialToken(ctx, hash)
		if err != nil {
			return "", fmt.Errorf("store the provided initial admin token: %w", err)
		}
		if !stored && state.InitialTokenHash != hash {
			slog.Warn("UNIFIED_INITIAL_ADMIN_TOKEN is ignored: an initial admin token was already issued")
		}
		return "", nil
	}

	if sso || state.InitialTokenHash != "" {
		return "", nil
	}

	// Pick the directory first: once the hash is claimed, the value has to be
	// recoverable from a file.
	dir, err := firstWritableDir(dirs)
	if err != nil {
		return "", err
	}
	token, err := controller.GenerateInitialToken()
	if err != nil {
		return "", fmt.Errorf("generate the initial admin token: %w", err)
	}
	stored, err := st.ClaimInitialToken(ctx, controller.HashToken(token))
	if err != nil {
		return "", fmt.Errorf("store the initial admin token: %w", err)
	}
	if !stored {
		slog.Info("the initial admin token was generated by another controller replica")
		return "", nil
	}
	path := filepath.Join(dir, controller.InitialTokenFileName)
	if err := writeSecretFile(path, token); err != nil {
		return "", fmt.Errorf("write the initial admin token: %w", err)
	}
	slog.Info(fmt.Sprintf("initial admin token written to %s; exchange it with \"unified-cli bootstrap\"", path))
	return path, nil
}

// firstWritableDir returns the first directory in dirs where a file can be
// created.
func firstWritableDir(dirs []string) (string, error) {
	for _, d := range dirs {
		if d == "" {
			continue
		}
		f, err := os.CreateTemp(d, ".initial-admin-token-probe-*")
		if err != nil {
			continue
		}
		name := f.Name()
		_ = f.Close()
		_ = os.Remove(name)
		return d, nil
	}
	return "", errNoWritableDir
}

// writeSecretFile writes value to path with mode 0600. Any existing file or
// symlink is removed first and the new file is created exclusively.
func writeSecretFile(path, value string) error {
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	if _, err := f.WriteString(value); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}
